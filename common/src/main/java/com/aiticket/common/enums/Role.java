package com.aiticket.common.enums;

/**
 * 账号身份。
 *
 * <p>身份决定**默认给你看什么**（大厅顶上那几张统计卡按身份分叉），**不等于**把一个
 * 账号永久锁死在一边：某个工单里能做什么，按"这一单里我站哪边"（creator_id /
 * handler_id）判。这条是 2026-04-18「所有用户均可接单」那次合并的答案，别再合回去。
 *
 * <p>分叉的位置变过一次，措辞得跟着走：此前分叉在侧边栏菜单上，所以这里原本写的是
 * "身份决定默认视图（菜单分叉）"。现在侧边栏统一了、不再按身份增减条目，分叉挪到了
 * 大厅的卡片上 —— 别照着旧措辞做决定。
 *
 * <p>库里存量 11 个账号一个都不迁移（改任一值都会丢功能）。
 */
public enum Role {
    /** 存量兼容：发布需求与接单开发都能做（库里 6 个老账号继续用这个值）。 */
    USER,
    /** 接单者 / 开发者：可接单开发。 */
    HANDLER,
    /** 发布者：发需求找人做。（与 HANDLER 对称，不是"能发布"的独占权限 ——
     *  任何身份都能发需求，这个值只决定大厅默认展示哪几张卡。） */
    PUBLISHER,
    /** 管理员 */
    ADMIN
}
