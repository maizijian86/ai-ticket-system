package com.aiticket.common.enums;

/**
 * 账号身份 —— 只有三种。
 *
 * <p>身份决定**默认给你看什么**（大厅顶上那几张统计卡按身份分叉），**不等于**把一个
 * 账号永久锁死在一边：某个工单里能做什么，按"这一单里我站哪边"（creator_id /
 * handler_id）判。这条是 2026-04-18「所有用户均可接单」那次合并的答案，别再合回去。
 *
 * <p>分叉的位置变过一次，措辞得跟着走：此前分叉在侧边栏菜单上，所以这里原本写的是
 * "身份决定默认视图（菜单分叉）"。现在侧边栏统一了、不再按身份增减条目，分叉挪到了
 * 大厅的卡片上 —— 别照着旧措辞做决定。
 *
 * <p><b>2026-10 移除了 USER（原来那个"发布与接单都能做"的存量兼容值）。</b>
 * 它是个含混的中间态：既然任何身份都能发需求也能接单（见上），单独留一个"两者都能"
 * 的值就没有信息量，反而让前端每处展示多一个分支、后台筛选多一个选项。
 * 库里的存量数据已按规则迁移：有发布记录的 → {@link #PUBLISHER}，其余 → {@link #HANDLER}。
 *
 * <p>⚠️ <b>枚举名不能改</b>：数据库里存的是名字（{@code @Enumerated(EnumType.STRING)}），
 * 改一个字母就得写迁移。中文叫法只在界面上用（发布者 / 接单者 / 管理员）。
 */
public enum Role {
    /** 接单者 / 开发者：接单开发。也是注册时的默认值（见 User 与 UserService） */
    HANDLER,
    /** 发布者：发需求找人做。（与 HANDLER 对称，不是"能发布"的独占权限 ——
     *  任何身份都能发需求，这个值只决定大厅默认展示哪几张卡、个人统计页的默认视角。） */
    PUBLISHER,
    /** 管理员 */
    ADMIN
}
