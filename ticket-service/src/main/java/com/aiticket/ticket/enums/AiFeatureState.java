package com.aiticket.ticket.enums;

/**
 * 某个功能在某张工单上"现在能不能按"—— 前端据此决定渲染遮罩、按钮还是已生成内容。
 *
 * <p>这四种状态对应四种完全不同的文案，所以不能压成一个布尔值：用户看到
 * "登录后可用"和"接单后可用"要做的动作不一样，看到"已使用"则应该放弃重试。
 */
public enum AiFeatureState {
    /** 我是接单人、该功能还没用过，可以用（额度不足时由 balance 单独表达） */
    AVAILABLE,
    /** 我是接单人、上次调用还在进行中（重复提交被挡） */
    IN_PROGRESS,
    /** 该工单的这个功能已经被用掉了（工单级，不区分是谁用的） */
    USED,
    /** 我不是该工单的接单人（含未登录），连入口都不该给 */
    NOT_HANDLER
}
